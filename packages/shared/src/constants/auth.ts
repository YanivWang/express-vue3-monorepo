/**
 * 会话标记 Cookie 的名字。
 *
 * 它是一枚**故意做成 JS 可读**的标记位，值无意义（恒为 `1`），与刷新令牌 Cookie 同生共死：
 * 登录与每次刷新时一起下发，登出与刷新失败时一起清除。
 *
 * 为什么需要它：访问令牌只驻内存，刷新页面必然丢失，于是前端启动时要用刷新 Cookie 静默换一枚回来。
 * 但刷新 Cookie 是 HttpOnly 的，前端无从判断「这台浏览器到底有没有会话」，
 * 结果只能**无条件**发一次 `POST /api/auth/refresh`——匿名访客也发，而且必然 401。
 *
 * 这带来两个真实后果：
 * 1. 刷新接口那一档限流是 `skipSuccessfulRequests`（只统计失败），于是「一次匿名首屏 = 一次计数」。
 *    同一出口 IP（公司 NAT、CGNAT、CDN 回源）上每分钟够数的匿名首屏就能打满桶，
 *    之后**该 IP 上真正登录的用户**刷新拿 429 → 会话恢复失败 → 被登出。
 *    限流本是为了防滥用，实际效果却成了把自己人锁在门外。
 * 2. 首屏被这次注定失败的请求阻塞（会话恢复必须先于路由挂载），所有访客都白等一个 API 往返。
 *
 * 有了标记位，前端就能在**不接触** HttpOnly Cookie 的前提下知道「本机可能有会话」：
 * 没有标记 = 确定没登录 → 根本不发请求。标记可能过期或被清（那就退化成一次失败的刷新），
 * 但它绝不构成凭证——它不含任何信息，伪造它最多让自己多发一次注定 401 的请求。
 */
export const SESSION_HINT_COOKIE_NAME = "evm_has_session";

/** 会话标记 Cookie 的值；只关心「在不在」，不关心内容 */
export const SESSION_HINT_COOKIE_VALUE = "1";
